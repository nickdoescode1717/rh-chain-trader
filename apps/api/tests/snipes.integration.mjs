if(process.argv[2]==='restart'){await evaluateSnipe(process.argv[3]);process.exit(0);}
const sql=postgres(process.env.DATABASE_URL),db=createDb(process.env.DATABASE_URL);
// The guarded database contains only fixtures; never run this against production.
await sql`truncate paper_snipes,paper_accounts,paper_ledger,paper_fills,paper_sell_intents,positions,purchase_proposals,identity_reviews,identity_claims,market_quotes,rpc_usage cascade`;
await sql`insert into research_projects(handle,domain) values('snipefixture','snipefixture.org'),('snipeother','snipeother.org')`;
await sql`insert into collection_control(id) values(1) on conflict do nothing`;
const app=new Hono();app.route('/paper-snipes',snipeRoutes);
const token='0x'+'a'.repeat(40),deployer='0x'+'b'.repeat(40),hash='0x'+'c'.repeat(64);
const terms={projectHandle:'snipefixture',deployerAddress:deployer,spendEth:'0.7',maxUnitPriceEth:'0.002',mode:'paper',chainId:4663,actor:'telegram:42'};
const post=async(path,body,secret=process.env.TELEGRAM_APPROVAL_TOKEN)=>{
 const r=await app.request('/paper-snipes'+path,{method:'POST',headers:{'content-type':'application/json','x-telegram-approval-token':secret},body:JSON.stringify(body)});return {status:r.status,body:await r.json()};};
assert.equal((await post('',{...terms,actor:'grok'})).status,403);
assert.equal((await post('',terms,'wrong')).status,403);
assert.equal((await post('',{...terms,chainId:46630})).status,400);
assert.equal((await post('',{...terms,mode:'live'})).status,400);
const p=(await post('',terms)).body.data;assert.ok(p.id);
assert.equal((await post('',terms)).body.data.id,p.id);
await assert.rejects(()=>sql`update paper_snipes set terms=terms || '{"spendEth":"1"}'::jsonb where id=${p.id}`);
const decision=(id,action,extra={})=>post('/'+id+'/'+action,{actor:'telegram:42',...extra});
await changeCollection(db,'stop','telegram:42');assert.equal((await decision(p.id,'arm')).status,409);
await changeCollection(db,'chainon','telegram:42');assert.equal((await decision(p.id,'arm')).status,200);
await sql`update paper_snipes set armed_at=now()-interval '30 seconds' where id=${p.id}`;
const p2=(await post('',{...terms,projectHandle:'snipeother'})).body.data;
assert.equal((await decision(p2.id,'arm')).body.error,'insufficient_unreserved_paper_cash');
assert.equal((await withLedger(tx=>reservedSnipeEth(tx))).toString(),'700000000000000000');
assert.equal((await ledgerBook()).balance.availableCashEth,'0.3');
assert.equal((await evaluateSnipe(p.id)).reason,'one_reviewed_mainnet_identity_required');
const report={version:1,source:{status:'matched',hash:'reviewed',reason:'match'},chain:{status:'matched',reason:'match',blockHash:hash,blockTimestamp:Math.floor(Date.now()/1000)-20}};
const [claim]=await sql`insert into identity_claims(project_handle,domain,source_url,token_address,deployer_address,creation_tx_hash,report,checked_at,reviewed_at,reviewed_by,reviewed_source_hash)
 values('snipefixture','snipefixture.org','https://snipefixture.org/token',${token},${deployer},${hash},${sql.json(report)},now(),now(),'telegram:42','reviewed') returning id`;
const q={chainId:4663,tokenAddress:token,source:'dexscreener',pairId:hash,quoteAddress:'0x'+'0'.repeat(40),priceEth:0.001,priceUsd:2,liquidityUsd:10000,observedAt:new Date().toISOString(),sourceUpdatedAt:null,url:'https://dexscreener.com/robinhood/fixture'};
const refresh=async(overrides={})=>sql`insert into market_quotes(token_address,quote,last_attempt_at) values(${token},${sql.json({...q,...overrides})},now()) on conflict(token_address) do update set quote=excluded.quote,last_error=null`;
await refresh();
const [manual]=await sql`insert into purchase_proposals(project_handle,token_address,size,status) values('snipefixture',${token},'eth:0.4','pending_nick') returning id`;
await assert.rejects(()=>ledgerBuy(manual.id,'telegram:42'),/insufficient_paper_cash/);
await sql`update identity_claims set checked_at=now()-interval '6 minutes' where id=${claim.id}`;
assert.equal((await evaluateSnipe(p.id)).reason,'identity_unverified');
await sql`update identity_claims set checked_at=now(),report=${sql.json({...report,chain:{...report.chain,blockTimestamp:Math.floor(Date.now()/1000)-600}})} where id=${claim.id}`;
assert.equal((await evaluateSnipe(p.id)).reason,'deployment_must_follow_arming');
await sql`update identity_claims set report=${sql.json(report)} where id=${claim.id}`;
await refresh({priceEth:0.003});assert.equal((await evaluateSnipe(p.id)).reason,'price_above_approved_limit');
await refresh({liquidityUsd:100});assert.equal((await evaluateSnipe(p.id)).reason,'insufficient_liquidity');
await refresh({observedAt:new Date(Date.now()-100_000).toISOString()});assert.equal((await evaluateSnipe(p.id)).reason,'waiting_for_fresh_tradable_quote');
await refresh();
// A late settlement failure must roll back proposal, fill and cash together.
await sql.unsafe("CREATE FUNCTION fail_snipe_fill() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'fixture rollback'; END $$; CREATE TRIGGER fail_snipe_fill BEFORE INSERT ON paper_fills FOR EACH ROW EXECUTE FUNCTION fail_snipe_fill();");
await assert.rejects(()=>evaluateSnipe(p.id));
assert.equal((await sql`select count(*)::int as n from paper_fills`)[0].n,0);
assert.equal((await sql`select count(*)::int as n from purchase_proposals where status='pending_snipe'`)[0].n,0);
assert.equal((await sql`select cash::text from paper_accounts where currency='ETH'`)[0].cash,'1.000000000000000000');
await sql.unsafe('DROP TRIGGER fail_snipe_fill ON paper_fills; DROP FUNCTION fail_snipe_fill();');
const results=await Promise.all([evaluateSnipe(p.id),evaluateSnipe(p.id)]);assert.ok(results.every(r=>r.status==='filled'));
assert.equal((await sql`select count(*)::int as n from paper_fills`)[0].n,1);
assert.equal((await sql`select cash::text from paper_accounts where currency='ETH'`)[0].cash,'0.300000000000000000');
assert.equal((await withLedger(tx=>reservedSnipeEth(tx))).toString(),'0');
const restart=spawnSync(process.execPath,['tests/snipes.integration.mjs','restart',p.id],{encoding:'utf8'});assert.equal(restart.status,0,restart.stdout+restart.stderr);
assert.equal((await sql`select count(*)::int as n from paper_fills`)[0].n,1);
