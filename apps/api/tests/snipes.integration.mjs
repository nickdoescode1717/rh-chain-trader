await decision(p4.id,'arm');await sql`update paper_snipes set expires_at=now()-interval '1 second' where id=${p4.id}`;
assert.equal((await evaluateSnipe(p4.id)).status,'expired');
console.log('Paper snipe integration passed: owner authorization, testnet/live rejection, immutable terms, reservations vs manual buys, stale identity, launch time, liquidity/price, exactly one atomic fill, restart, expiry and stop cancellation.');
