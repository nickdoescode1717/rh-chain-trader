import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createDb,collectionState,changeCollection,permitCollection} from '@rh/db';
import {installCollectionControl} from '../dist/collection-control.js';
const postgres=createRequire(import.meta.resolve('@rh/db'))('postgres');
assert.match(new URL(process.env.DATABASE_URL).pathname,/^\/rh_pricing_test_[a-f0-9]{16}$/);
const sql=postgres(process.env.DATABASE_URL),db=createDb(process.env.DATABASE_URL);
await changeCollection(db,'stop','fixture');await assert.rejects(permitCollection(db,'eth_blockNumber'),/stopped/);
let network=0;process.env.RPC_URL='https://rpc.fixture.org/';
globalThis.fetch=async()=>{network++;return Response.json({result:'0x123'});};
installCollectionControl(db);
await assert.rejects(fetch(process.env.RPC_URL,{method:'POST',body:'{"method":"eth_blockNumber"}'}));assert.equal(network,0);
await changeCollection(db,'run','fixture');await fetch('https://website.fixture.org/');assert.equal(network,1);
await assert.rejects(fetch(process.env.RPC_URL,{method:'POST',body:'{"method":"eth_blockNumber"}'}));assert.equal(network,1);
await changeCollection(db,'chainon','fixture');await fetch(process.env.RPC_URL,{method:'POST',body:'{"method":"eth_blockNumber"}'});assert.equal(network,2);
assert.equal((await collectionState(db)).rpcRequestsToday,1);
await sql`insert into rpc_usage(day,method,attempts) values(to_char(now() at time zone 'UTC','YYYY-MM-DD'),'fixture',1998)`;
const results=await Promise.allSettled(Array.from({length:10},()=>permitCollection(db,'eth_call')));
assert.equal(results.filter(r=>r.status==='fulfilled').length,1);assert.equal((await collectionState(db)).rpcRequestsToday,2000);
await assert.rejects(fetch(process.env.RPC_URL,{method:'POST',body:'{"method":"eth_call"}'}));assert.equal(network,2);
await changeCollection(db,'stop','fixture');await assert.rejects(fetch('https://website.fixture.org/'));assert.equal(network,2);
console.log('Collection transport integration passed: no outbound calls while stopped, separate RPC enablement, atomic daily request guard and persistent state. No real network calls.');
await sql.end();process.exit(0);
