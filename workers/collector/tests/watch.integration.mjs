import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const postgres=createRequire(require.resolve('@rh/db'))('postgres');
import {createDb} from '@rh/db';
import {scanNextWatch} from '../dist/research/watch-loop.js';
assert.match(new URL(process.env.DATABASE_URL).pathname,/^\/rh_pricing_test_[a-f0-9]{16}$/);
const sql=postgres(process.env.DATABASE_URL),db=createDb(process.env.DATABASE_URL);
await sql`update watch_targets set enabled=false`;
const [watch]=await sql`insert into watch_targets(input_key,domain) values('site:fixture.org','fixture.org') returning *`;
const discovery={observedAt:new Date().toISOString(),primaryHandle:'fixturewatch',domain:'fixture.org',accounts:[],domains:[],links:[],addresses:[],gaps:[]};
const discover=async()=>({discovery:structuredClone(discovery),posts:[]});
const inspect=async()=>({evidence:[],rating:{rating10:null},subdomains:{},researchedAt:new Date().toISOString()});
const enrich=async()=>({status:'disabled',analysis:null});
await scanNextWatch(db,null,discover,inspect,enrich);
const [saved]=await sql`select * from watch_targets where id=${watch.id}`;
assert.equal(saved.status,'watching');assert.equal(saved.project_handle,'fixturewatch');
assert.equal((await sql`select * from identity_claims where project_handle='fixturewatch'`).length,0);
await scanNextWatch(db,null,async()=>{throw new Error('hourly schedule failed')},inspect,enrich);
await sql`update watch_targets set last_attempt_at=null where id=${watch.id}`;
await scanNextWatch(db,null,async()=>{
  await sql`update watch_targets set enabled=false,revision=revision+1 where id=${watch.id}`;
  return {discovery:{...discovery,primaryHandle:'unwanted'},posts:[]};
},inspect,enrich);
assert.equal((await sql`select * from research_projects where handle='unwanted'`).length,0);
await sql`update watch_targets set enabled=true,last_attempt_at=null where id=${watch.id}`;
await scanNextWatch(db,null,async()=>({discovery:{...discovery,domain:'copycat.org'},posts:[]}),inspect,enrich);
assert.equal((await sql`select domain from research_projects where handle='fixturewatch'`)[0].domain,'fixture.org');
assert.ok((await sql`select discovery from watch_targets where id=${watch.id}`)[0].discovery.gaps.includes('existing_project_mapping_requires_review'));
console.log('Collector watch integration passed: saved research, hourly claim, pause during collection, mapping conflict protection, no trust.');
await sql.end();process.exit(0);
